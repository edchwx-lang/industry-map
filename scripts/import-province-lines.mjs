import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const sourcePath=process.argv[2];
if(!sourcePath)throw new Error('Usage: node scripts/import-province-lines.mjs <original province GeoJSON>');
const bytes=await readFile(sourcePath),original=JSON.parse(bytes);
const sha256=data=>createHash('sha256').update(data).digest('hex');
const root=path.resolve(import.meta.dirname,'..');
const manifest=JSON.parse(await readFile(path.join(root,'boundary/manifest.json'),'utf8'));
const asset=manifest.assets.find(a=>a.id==='china-province');
if(sha256(bytes)!==asset.sourceSha256)throw new Error('Original source hash does not match bundled province provenance');
const lines={type:'FeatureCollection',features:original.features.filter(f=>['LineString','MultiLineString'].includes(f.geometry?.type))};
if(!lines.features.length)throw new Error('No original boundary lines found');
const output=Buffer.from(JSON.stringify(lines)+'\n');
const target=path.join(root,'boundary/china/province/tianditu-lines.geojson');
await writeFile(target,output,{flag:'wx'});
const metadata={source:'User-supplied 天地图/中国_省.geojson; original source hash verified',sourceSha256:sha256(bytes),sha256:sha256(output),featureCount:lines.features.length,segmentCount:lines.features.reduce((n,f)=>n+(f.geometry.type==='LineString'?1:f.geometry.coordinates.length),0),transformation:'select original line features without modifying coordinates; source names retained'};
await writeFile(target.replace('.geojson','.metadata.json'),JSON.stringify(metadata,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify(metadata));
